#!/usr/bin/env bash
# ==============================================================================
# Buildbox — Devcontainer Host Pre-Flight (`initializeCommand`)
# ==============================================================================
# Runs on the host BEFORE Docker/Podman Compose starts the devcontainer:
#   1. Copies `.env.example` -> `.env` on fresh clones so local env is ready.
#   2. Generates gitignored `.devcontainer/docker-compose.local.yml`:
#      - Rootless Podman (Fedora Atomic / Linux): injects `userns_mode: keep-id`,
#        `security_opt: [label:disable]` for SELinux bind mounts, `oom_score_adj`
#        parity with systemd `app.slice`, and NVIDIA CDI GPU passthrough when
#        `/etc/cdi/nvidia.yaml` is present.
#      - Docker Desktop / OrbStack / Colima / GitHub Codespaces / CI: writes an
#        empty `services: {}` override.
#
# Uses Bash 3.2-compatible syntax so it executes safely under macOS `/bin/bash`.
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
LOCAL_OVERRIDE="${SCRIPT_DIR}/docker-compose.local.yml"

if [ ! -f "${REPO_ROOT}/.env" ] && [ -f "${REPO_ROOT}/.env.example" ]; then
    cp "${REPO_ROOT}/.env.example" "${REPO_ROOT}/.env"
    echo "[devcontainer init] Created .env from .env.example"
fi

is_podman_rootless=false
docker_bin=""
if command -v docker >/dev/null 2>&1; then
    docker_bin="$(command -v docker)"
elif [ -x "${HOME}/.local/bin/docker" ]; then
    docker_bin="${HOME}/.local/bin/docker"
fi

if [ -n "${docker_bin}" ]; then
    info_out="$("${docker_bin}" info 2>/dev/null || true)"
    if printf '%s\n' "${info_out}" | grep -q 'rootless' && \
       printf '%s\n' "${info_out}" | grep -qiE 'crun|CDI spec directories|podman'; then
        is_podman_rootless=true
    fi
fi

has_nvidia_cdi=false
if [ -f /etc/cdi/nvidia.yaml ] || [ -f /var/run/cdi/nvidia.yaml ]; then
    has_nvidia_cdi=true
elif command -v nvidia-ctk >/dev/null 2>&1 && nvidia-ctk cdi list 2>/dev/null | grep -q 'nvidia.com/gpu'; then
    has_nvidia_cdi=true
fi

if [ "${is_podman_rootless}" = true ]; then
    # Under systemd user app.slice (e.g. Fedora KDE OOMScoreAdjust=200), Podman's
    # Docker-compat API clamps omitted OomScoreAdj (0) to the daemon's value on create
    # while exec/healthcheck still attempts 0 -> EACCES. Setting oom_score_adj
    # explicitly on Compose services keeps create, exec, and healthchecks consistent.
    podman_oom_adj=0
    if command -v systemctl >/dev/null 2>&1; then
        svc_oom="$(systemctl --user show podman.service -p OOMScoreAdjust --value 2>/dev/null || true)"
        if [[ "${svc_oom}" =~ ^-?[0-9]+$ ]] && [ "${svc_oom}" -gt "${podman_oom_adj}" ]; then
            podman_oom_adj="${svc_oom}"
        fi
    fi
    if [ -r /proc/self/oom_score_adj ]; then
        self_oom="$(cat /proc/self/oom_score_adj 2>/dev/null || echo 0)"
        if [[ "${self_oom}" =~ ^-?[0-9]+$ ]] && [ "${self_oom}" -gt "${podman_oom_adj}" ]; then
            podman_oom_adj="${self_oom}"
        fi
    fi

    {
        echo "# Auto-generated by .devcontainer/init-host.sh for rootless Podman"
        echo "services:"
        if [ "${podman_oom_adj}" -gt 0 ]; then
            echo "  db:"
            echo "    oom_score_adj: ${podman_oom_adj}"
            echo "  redis:"
            echo "    oom_score_adj: ${podman_oom_adj}"
        fi
        echo "  dev:"
        echo "    userns_mode: keep-id"
        echo "    security_opt:"
        echo "      - label:disable"
        if [ "${podman_oom_adj}" -gt 0 ]; then
            echo "    oom_score_adj: ${podman_oom_adj}"
        fi
        if [ "${has_nvidia_cdi}" = true ]; then
            echo "    deploy:"
            echo "      resources:"
            echo "        reservations:"
            echo "          devices:"
            echo "            - driver: cdi"
            echo "              device_ids:"
            echo "                - nvidia.com/gpu=all"
            echo "              capabilities:"
            echo "                - gpu"
        fi
    } > "${LOCAL_OVERRIDE}"
    echo "[devcontainer init] Configured rootless Podman override (keep-id, label:disable, oom_score_adj=${podman_oom_adj}, nvidia_cdi=${has_nvidia_cdi})"
else
    printf 'services: {}\n' > "${LOCAL_OVERRIDE}"
    echo "[devcontainer init] Configured standard Docker/Codespaces override"
fi
